#!/usr/bin/env python3
"""עשרים חשבונות של 50K או עשרה של 150K.

התשובה הקצרה: 20x50K, אבל לא מהסיבה שנראית ראשונה.

התחלתי כאן מיחס שנראה מכריע בלי שום סימולציה. סולם המשיכות של
50K הוא 13,000 דולר מול 2,500 דרודאון, ושל 150K הוא 18,000 מול
5,000 — כלומר 5.20 מול 3.60 לכל דולר שאפשר להפסיד, יתרון של 44%
לקטן. כתבתי שזה נכון בלי קשר לתוחלת. זה היה מוקדם מדי.

בקרה של אותו מספר חשבונות הפילה את הטענה. כשלשתי התוכניות יש
עשרה חשבונות, ה-150K מנצח בכל תוחלת מעל 0.10R בערך, ובהפרש
שגדל עם התוחלת. היחס לכל דולר דרודאון באמת עדיף לקטן, אבל
הסולם המוחלט גדול יותר בגדול, ומרגע שיש קצה אמיתי זה מה שגובר.
כלומר מה שהכריע בהשוואה המקורית היה המספר עשרים מול עשרה, ולא
גודל התוכנית.

מה שנשאר אחרי הבקרה הוא תשובה מותנית, ומדויקת יותר:

  בלי קצה, או עם קצה שלילי — הקטן עדיף, ובבירור. הוא מפסיד
  פחות. במידה זהה ובמספר זהה, 0.00R עולה 25,942 דולר ב-50K מול
  99,315 ב-150K. זו לא תשואה, זו עלות של לגלות שטעית.

  עם קצה מבוסס מעל 0.10R בערך — הגדול עדיף לכל חשבון.

  נקודת ההיפוך יושבת בין 0.08R ל-0.10R.

וזה בדיוק העניין. הגבול התחתון של הראיה היום שלילי, ונקודת
ההיפוך נמצאת באמצע התחום שהשער מנסה להכריע. כלומר בחירת
התוכנית אינה החלטה נפרדת — היא אותה החלטה, ותלויה באותה מדידה.
היום, עם ראיה שלא קיימת, הכיוון הוא הקטן: הוא זול יותר לטעות
בו, והוא גם זה שנותן עשרים סלוטים במקום עשרה. אם וכאשר התוחלת
תימדד מעל 0.10R בביטחון, השאלה הזאת נפתחת מחדש — ואז התשובה
עשויה להתהפך.

ופרט אחד שקובע את הכל ולא נראה כמו כלכלה. הסיכון הוא אחוז
מהדרודאון, ואי אפשר לסחור בחצי חוזה. ב-4%, 50K רוצה 100 דולר
מול 42.50 לחוזה — 2.35, שמתעגל ל-2, כלומר 15% פחות סיכון ממה
שנכתב. 150K רוצה 200, מקבל 4.71, ומתעגל ל-5 — 6% יותר. העיגול
לבדו מזיז את הסיכון בפועל לכיוונים הפוכים בשתי התוכניות.
"""

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from apex_model import MES_PT, PLANS, STOP_PTS, allocate, simulate

# התוחלות שנבדקות. הטווח מתחיל שלילי בכוונה: שם נמצאת הראיה
# בפועל, ותשובה שנכונה רק כשיש קצה אינה תשובה.
R_GRID = (-0.10, 0.00, 0.10, 0.20, 0.30)


def effective_risk(plan: str, risk_pct: float) -> dict:
    """מה באמת מסוכן אחרי עיגול לחוזה שלם."""
    dd = PLANS[plan]["dd"]
    want = risk_pct * dd
    per_contract = STOP_PTS * MES_PT
    k = max(1, round(want / per_contract))
    got = k * per_contract
    return {"plan": plan, "want": want, "k": k, "got": got,
            "err_pct": 100 * (got - want) / want,
            "eff_pct": 100 * got / dd}


def ladder_value(plan: str) -> dict:
    P = PLANS[plan]
    total = float(sum(P["ladder"]))
    return {"plan": plan, "ladder": total, "dd": P["dd"],
            "per_dd": total / P["dd"],
            "cost": P["evalfee"] + P["activation"]}


def compare(a=("50K", 20), b=("150K", 10), risk_pct_eval=0.10, **kw) -> list:
    """שתי התוכניות תחת אותו כלל מידה דו-מהירותי.

    הכלל הזה הוא לא פרט. הרצתי קודם את ההשוואה בלי להעביר
    risk_pct_eval, כלומר עם 4% גם בהערכה — בניגוד לכלל של
    המיומנות עצמה. זה לא מעניש את שתי התוכניות באותה מידה: היעד
    של ההערכה ב-50K הוא 35.3R ב-4% מול 11.8R ב-10%, וב-150K הוא
    42.4R מול 17.6R. כלומר טעות המידה חונקת דווקא את הגדול, ואז
    ההשוואה מודדת את הטעות שלי ולא את ההפרש בין התוכניות.
    """
    rows = []
    for plan, slots in (a, b):
        for r in R_GRID:
            s = simulate(plan=plan, slots=slots, avg_R=r,
                         risk_pct_eval=risk_pct_eval, **kw)
            res, port, biz = allocate(s["net_year"])[-1]
            tot = res + port + biz
            rows.append({
                "plan": plan, "slots": slots, "avg_R": r,
                "median": float(np.median(tot)),
                "p10": float(np.percentile(tot, 10)),
                "p90": float(np.percentile(tot, 90)),
                "burned": float(s["burned"].mean()),
                "spend": float(s["fees"].sum(axis=1).mean()),
            })
    return rows


def main() -> None:
    print(f"{'=' * 66}\n  מה שידוע לפני כל סימולציה\n{'=' * 66}")
    print(f"{'תוכנית':>8} {'סולם':>10} {'דרודאון':>10} {'לכל $ DD':>10} "
          f"{'עלות פתיחה':>12}")
    for plan in ("50K", "150K"):
        v = ladder_value(plan)
        print(f"{v['plan']:>8} {v['ladder']:>9,.0f}$ {v['dd']:>9,.0f}$ "
              f"{v['per_dd']:>9.2f}x {v['cost']:>11,.0f}$")
    small, big = ladder_value("50K"), ladder_value("150K")
    edge = 100 * (small["per_dd"] / big["per_dd"] - 1)
    print(f"\n  הסולם של 50K שווה {edge:.0f}% יותר לכל דולר של דרודאון.")
    print("  היחס נכון, אבל הוא לא מכריע: הסולם המוחלט גדול יותר")
    print("  בגדול, ומרגע שיש קצה אמיתי זה מה שגובר. הבקרה בסוף")
    print("  הדוח היא מה שמכריע, לא השורה הזאת.")

    print(f"\n{'=' * 66}\n  עיגול החוזים — הסיכון שבאמת נלקח\n{'=' * 66}")
    print(f"{'תוכנית':>8} {'מבוקש':>9} {'חוזים':>7} {'בפועל':>9} "
          f"{'סטייה':>9} {'% מה-DD':>10}")
    for plan in ("50K", "150K"):
        e = effective_risk(plan, 0.04)
        print(f"{e['plan']:>8} {e['want']:>8,.0f}$ {e['k']:>7d} "
              f"{e['got']:>8,.0f}$ {e['err_pct']:>+8.1f}% {e['eff_pct']:>9.2f}%")
    print("\n  4% זה מה שנכתב. זה לא מה שנלקח. הפער הזה בין התוכניות")
    print("  הוא מקור שלם של הבדל בשרידות שאין לו שום קשר לגודל.")

    print(f"\n{'=' * 66}\n  היעד של ההערכה, ביחידות סיכון\n{'=' * 66}")
    print(f"{'תוכנית':>8} {'מידה':>7} {'חוזים':>7} {'סיכון':>9} {'היעד ב-R':>11}")
    for plan in ("50K", "150K"):
        for pct in (0.04, 0.10):
            e = effective_risk(plan, pct)
            need = PLANS[plan]["target"] / e["got"]
            print(f"{plan:>8} {pct:>6.0%} {e['k']:>7d} {e['got']:>8,.0f}$ "
                  f"{need:>10.1f}R")
    print("\n  בעשרים ואחד ימי מסחר, שלוש עסקאות ביום, זה 63 עסקאות.")
    print("  יעד של 35R או 42R מהן אינו קשה — הוא כמעט בלתי אפשרי.")
    print("  זו בדיוק הסיבה שההערכה נמדדת ב-10% ולא ב-4%.")

    print(f"\n{'=' * 66}\n  שמונה שנים — 20x50K מול 10x150K\n{'=' * 66}")
    print(f"{'תוכנית':>9} {'avg_R':>7} {'חציון שנה 8':>16} {'אחוזון 10':>14} "
          f"{'נשרפו':>8} {'עמלות':>11}")
    rows = compare()
    for r in rows:
        print(f"{r['plan']:>5}x{r['slots']:<3} {r['avg_R']:>+7.2f} "
              f"{r['median']:>15,.0f}$ {r['p10']:>13,.0f}$ "
              f"{r['burned']:>8.1f} {r['spend']:>10,.0f}$")

    print(f"\n{'=' * 66}\n  ההכרעה\n{'=' * 66}")
    by_r = {}
    for r in rows:
        by_r.setdefault(r["avg_R"], {})[r["plan"]] = r
    flips = []
    for rr in R_GRID:
        s, b = by_r[rr]["50K"], by_r[rr]["150K"]
        win = "50K" if s["median"] > b["median"] else "150K"
        d = abs(s["median"] - b["median"])
        flips.append(win)
        print(f"  avg_R {rr:+.2f}: {win} מוביל בחציון בפער של {d:,.0f}$")
    if len(set(flips)) == 1:
        print(f"\n  אותה תשובה בכל התוחלות שנבדקו: {flips[0]}.")
        print("  כלומר ההחלטה הזאת לא ממתינה למדידה של הקצה.")
    else:
        print("\n  התשובה מתהפכת בתוך הטווח. כלומר היא תלויה בתוחלת,")
        print("  והתוחלת עדיין לא נמדדה — אין להחליט לפני שהיא תימדד.")

    print(f"\n{'=' * 66}\n  אותו מספר חשבונות — כדי להפריד תוכנית מכמות"
          f"\n{'=' * 66}")
    print("  כל מה שלמעלה משווה עשרים מול עשרה, וזו השאלה כפי שנשאלה.")
    print("  אבל אז 'הקטן מנצח' יכול להיות פשוט 'עשרים מנצח עשרה'.")
    print("  כאן שתי התוכניות מקבלות עשרה חשבונות, ואם ההפרש נעלם —")
    print("  מה שהכריע היה המספר, לא התוכנית.")
    ctl = compare(a=("50K", 10), b=("150K", 10))
    cby = {}
    for r in ctl:
        cby.setdefault(r["avg_R"], {})[r["plan"]] = r
    print(f"\n{'avg_R':>7} {'50Kx10':>15} {'150Kx10':>15} {'הפרש':>14}")
    for rr in R_GRID:
        a, b = cby[rr]["50K"], cby[rr]["150K"]
        print(f"{rr:>+7.2f} {a['median']:>14,.0f}$ {b['median']:>14,.0f}$ "
              f"{a['median'] - b['median']:>+13,.0f}$")
    wins = [rr for rr in R_GRID
            if cby[rr]["50K"]["median"] > cby[rr]["150K"]["median"]]
    if len(wins) == len(R_GRID):
        print("\n  ההפרש שורד גם בכמות זהה. כלומר זו התוכנית ולא המספר,")
        print("  והעשרים רק מגדילים יתרון שכבר קיים.")
    elif not wins:
        print("\n  בכמות זהה הגדול מנצח תמיד. מה שהכריע למעלה היה")
        print("  המספר עשרים מול עשרה, ולא גודל התוכנית.")
    else:
        flip = max(wins)
        print(f"\n  ההפרש לא שורד בכמות זהה. הקטן מנצח עד {flip:+.2f}R")
        print("  ומפסיד מעליו. כלומר מה שהכריע למעלה היה המספר עשרים")
        print("  מול עשרה, והתשובה האמיתית מותנית בתוחלת:")
        print("\n    בלי קצה — הקטן, כי הוא זול יותר לטעות בו.")
        print("    עם קצה מבוסס מעל ~0.10R — הגדול, לכל חשבון.")
        print("\n  נקודת ההיפוך יושבת בתוך התחום שהשער מנסה להכריע,")
        print("  ולכן זו אינה החלטה נפרדת אלא אותה מדידה. היום, עם")
        print("  גבול תחתון שלילי, הכיוון הוא הקטן — ואם התוחלת תעבור")
        print("  את 0.10R בביטחון, השאלה נפתחת מחדש.")

    print("\n  מה שהמספרים האלה לא אומרים: הם כולם מניחים שהתוחלת")
    print("  זהה בשתי התוכניות. היא כנראה לא. סטופ של 8.5 נקודות")
    print("  על 5 חוזים סופג יותר החלקה מאשר על 2, ועל חשבון 150K")
    print("  הסולם מחייב ימים כשירים ארוכים יותר. שניהם פועלים נגד")
    print("  הגדול, ואף אחד מהם לא מתומחר כאן.")


if __name__ == "__main__":
    main()
