def by_cat() -> dict:
    out: dict = {}
    for h in REGISTER:
        out.setdefault(h.cat, []).append(h)
    return out


def testable_now() -> list:
    """מה שאפשר לבדוק היום מהקובץ שכבר קיים."""
    return [h for h in REGISTER if h.test and h.needs in ("replay", "bars")]


def ranked() -> list:
    """לפי ערך מידע, לא לפי כמה זה נשמע מבטיח."""
    return sorted(REGISTER, key=lambda h: -h.voi)


def bonferroni_threshold(se: float, n: int, alpha: float = 0.05) -> float:
    """איזה אפקט נדרש כדי לשרוד תיקון לבדיקה מרובה."""
    from statistics import NormalDist
    return NormalDist().inv_cdf(1 - alpha / (2 * max(n, 1))) * se


