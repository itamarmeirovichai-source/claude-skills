#!/usr/bin/env python3
"""כמה אפשר להעלות את האחוז, וכמה זה עולה.

השאלה "תעשה שיהיה את האחוזים הגבוהים" היא שאלה לגיטימית עם תשובה
מדידה, ולכן היא נענית כאן במספרים ולא בהטפה.

יש בדיוק ארבעה חוגים שאפשר לסובב, ורק שניים מהם אמיתיים:

  גודל הסיכון — עובד, ובגדול. 4% -> 8% מעלה 24.6% ל-38.2% בתוחלת
  0.30R. אבל החוג הזה הוא מכפיל על הסימן, לא יוצר סימן: בתוחלת
  שלילית הוא מכפיל גם את ההפסד, ומספר החשבונות שנשרפים עולה מ-54
  ל-178 בתוחלת חיובית ומ-2,242 ל-2,576 בשלילית.

  מספר החשבונות — לא עובד בכלל. האחוז זהה ב-10 וב-20 חשבונות.
  הוספת חשבונות מכפילה דולרים, לא תשואה, ובתוחלת שלילית היא
  מכפילה את ההפסד.

  סיווג המס — עובד, בחינם. ההפרש בין 25% ל-47% הוא 7.2 נקודות
  אחוז, בלי אף חשבון נוסף שנשרף. זה כמעט בדיוק מה שמעבר מ-4%
  ל-6% סיכון נותן (7.6 נקודות) — רק בלי להכפיל את קצב המוות.

  האסטרטגיה עצמה — לא חוג. כוונון מחדש כדי לעבור את הסף הוא
  התאמה לרעש, וזו הטעות היקרה ביותר שזמינה כאן.

הדרך הנכונה לקרוא את הטבלה שהסקריפט מדפיס: גודל הסיכון לא קונה
תשואה, הוא קונה רף נמוך יותר לאסטרטגיה. ב-4% צריך 0.300R כדי
להגיע ל-24.6%; ב-8% צריך 0.211R. כלומר הסיכון הכפול קנה 0.089R
של מרווח. זה מה שהוא, וככה צריך להחליט עליו — לא כ"יותר תשואה".
"""

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from apex_model import simulate

RISKS = (0.02, 0.04, 0.06, 0.08, 0.12)
R_GRID = (-0.10, 0.00, 0.10, 0.20, 0.30, 0.35)
SLOTS, NOMINAL = 20, 20 * 50_000


def grid(n=600, seed=11) -> dict:
    out = {}
    for r in R_GRID:
        for p in RISKS:
            s = simulate(plan="50K", slots=SLOTS, avg_R=r, risk_pct=p,
                         risk_pct_eval=0.10, n=n, seed=seed)
            # מצב יציב: שנים 5 עד 8. השנים הראשונות הן הרמפה, והן
            # מדללות את האחוז בכך שבהן עוד אין עשרים חשבונות.
            out[(r, p)] = (float(s["net_year"][:, 4:].mean()),
                           float(np.median(s["burned"])))
    return out


def needed_R(g: dict, p: float, target_pct: float):
    """איזו תוחלת דרושה כדי להגיע לאחוז מסוים בגודל סיכון נתון."""
    xs = np.array(R_GRID)
    ys = np.array([100 * g[(r, p)][0] / NOMINAL for r in R_GRID])
    if ys.max() < target_pct:
        return None
    i = int(np.searchsorted(ys, target_pct))
    if i == 0:
        return float(xs[0])
    return float(xs[i-1] + (target_pct - ys[i-1])
                 * (xs[i] - xs[i-1]) / (ys[i] - ys[i-1]))


def main() -> None:
    g = grid()
    print(f"{'=' * 62}\n  נטו לשנה כאחוז מההון הנומינלי, 20x50K, שנים 5-8"
          f"\n{'=' * 62}")
    print(f"{'תוחלת':>8}" + "".join(f"{p:>9.0%}" for p in RISKS))
    for r in R_GRID:
        print(f"{r:>+8.2f}" + "".join(
            f"{100*g[(r,p)][0]/NOMINAL:>8.1f}%" for p in RISKS))

    print(f"\n{'תוחלת':>8}" + "".join(f"{p:>9.0%}" for p in RISKS)
          + "   <- חשבונות שנשרפים ב-8 שנים")
    for r in R_GRID:
        print(f"{r:>+8.2f}" + "".join(f"{g[(r,p)][1]:>9.0f}" for p in RISKS))

    print(f"\n{'=' * 62}\n  מה הסיכון באמת קונה\n{'=' * 62}")
    print(f"{'סיכון':>8} {'ל-20%':>12} {'ל-24.6%':>12} {'נשרפים ב-0.30R':>16}")
    for p in RISKS:
        a, b = needed_R(g, p, 20.0), needed_R(g, p, 24.6)
        fa = f"{a:+.3f}R" if a else "לא מושג"
        fb = f"{b:+.3f}R" if b else "לא מושג"
        print(f"{p:>8.0%} {fa:>12} {fb:>12} {g[(0.30,p)][1]:>16.0f}")
    print("\n  גודל הסיכון לא קונה תשואה — הוא קונה רף נמוך יותר")
    print("  לאסטרטגיה, במחיר של קצב מוות גבוה יותר. זו ההחלטה")
    print("  האמיתית, וכדאי לקבל אותה בניסוח הזה ולא בניסוח של אחוזים.")

    print(f"\n{'=' * 62}\n  החוג היחיד שמעלה אחוז בלי להעלות סיכון\n{'=' * 62}")
    print(f"  מס 25%:  $246,311 לשנה = {100*246311/NOMINAL:.1f}%")
    print(f"  מס 47%:  $174,060 לשנה = {100*174060/NOMINAL:.1f}%")
    print(f"  ההפרש:   {100*(246311-174060)/NOMINAL:.1f} נקודות אחוז, "
          f"בלי אף חשבון נוסף שנשרף.")
    print("  זה כמעט בדיוק מה ש-4% -> 6% נותן, רק בלי להכפיל את")
    print("  קצב המוות. מכתב אחד לרואה חשבון, ולא הוצא דולר.")


if __name__ == "__main__":
    main()
