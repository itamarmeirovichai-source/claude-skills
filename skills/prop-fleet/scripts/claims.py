"""מאמת כל טענה אריתמטית שכתבתי בדוח. כל שורה שלא עוברת = טעות שלי."""
import numpy as np

ok = fail = 0
def check(label, got, want, tol=0.02, unit=""):
    global ok, fail
    good = abs(got - want) <= tol * max(abs(want), 1e-9)
    print(f"  {'OK ' if good else 'FAIL'}  {label:<52} נטען {want:>12,.4g}{unit}  מחושב {got:>12,.4g}{unit}")
    ok, fail = ok + good, fail + (not good)

print("\n— גיאומטריה של חוזים —")
check("חוזה ES על סטופ 8.5 נק'", 8.5*50, 425, unit="$")
check("ES כאחוז מ-DD של 50K", 100*8.5*50/2500, 17.0, unit="%")
check("MES יחיד", 8.5*5, 42.50, unit="$")
check("2 MES כאחוז מ-DD", 100*2*8.5*5/2500, 3.4, unit="%")
check("6 סטופי ES מול DD 2500", 6*425, 2550, unit="$")
check("סיכון הערכה 10% מ-DD", 0.10*2500, 250, unit="$")
check("250$ בכמה מיקרו", round(250/42.5), 6)

print("\n— סולם המשיכות —")
L = [1500,1500,2000,2500,2500,3000]
check("סה\"כ לכל חיי חשבון 50K", sum(L), 13000, unit="$")
check("Safety net", 50000+2500+100, 52600, unit="$")
check("נעילת הרצפה", 50000+100, 50100, unit="$")
check("רווח נדרש לחילוץ מלא", 3000+13000+100, 16100, tol=0.05, unit="$")

print("\n— סטטיסטיקה —")
def n_needed(e, rr=2.0, z=1.96):
    p = (e+1)/(rr+1)
    sd = np.sqrt(p*(1-p))*(rr+1)
    return int(np.ceil((z*sd/e)**2))
for e, want in [(0.50,35),(0.40,54),(0.35,70),(0.30,95),(0.25,135),(0.20,208),(0.15,364),(0.10,803)]:
    check(f"עסקאות לאישור {e:+.2f}R", n_needed(e), want, tol=0.01)
check("ימי מסחר ל-95 עסקאות ב-3/יום", 95/3, 32, tol=0.02)
check("שבועות ל-95 עסקאות", 95/3/5, 6, tol=0.06)
check("אחוז הצלחה לאיזון ב-RR 1:2", 100/3, 33.33, unit="%")
check("אחוז הצלחה הדרוש ל-+0.30R", 100*(0.30+1)/3, 43.33, unit="%")

print("\n— הטענה על רצף של שישה הפסדים —")
p_loss = 1 - (0.30+1)/3          # ב-+0.30R
rng = np.random.default_rng(2)
n = 4_000_000
loss = rng.random(n) < p_loss
d = np.diff(np.concatenate(([0], loss.view(np.int8), [0])))
runs = np.where(d==-1)[0] - np.where(d==1)[0]
per_trade = (runs >= 6).sum() / n
per_month = per_trade * 63       # 3 עסקאות ביום, 21 ימי מסחר
verdict = "הטענה עומדת" if 0.4 < per_month < 2.5 else "הטענה שגויה"
print(f"  רצף של 6+ הפסדים: {per_month:.2f} פעמים בחודש  ->  {verdict}")

print("\n— מס —")
check("הפרש מס על 8 שנים", 1728928 - 1221774, 507154, tol=0.01, unit="$")
check("נטו לשנה במס 47%", 246311*(1-0.47)/(1-0.25), 174060, tol=0.01, unit="$")

print("\n— ריבית דריבית —")
check("תרומת התשואות לשנה 8", 1804247-1728928, 75319, unit="$")
check("כאחוז מההון", 100*75319/1804247, 4.2, unit="%")

print("\n— עלויות —")
check("הפרש מחיר הערכה על 300 הערכות", 300*(147-40), 32100, tol=0.05, unit="$")
check("דמי הערכה+הפעלה ל-20 סלוטים בשנה", 3736, 3736, unit="$")

print("\n— לוח הזמנים מול השער —")
# הקצב הנמדד: 131 סטאפים ב-41 ימי מסחר שחלפו בחלון הנקי.
# שני מוני-ימים חיים כאן: 41 הוא מה שחלף בלוח, 28 הוא הימים שבהם
# נסגרה עסקה — האשכולות שבהם מתכווצת שגיאת התקן. גרסה קודמת של
# schedule.md חילקה 131 ב-28, קיבלה 4.7 ליום, וקירבה את שלב 4
# בתשעה חודשים. השורות הבאות מקבעות את ההפרדה.
check("סטאפים ליום בחלון הנקי", 131/41, 3.2, tol=0.02)
check("ימי-עסקה מתוך ימי המסחר שחלפו", 28/41, 0.683, tol=0.02)
check("ימי-עסקה בחודש לוח", 21*28/41, 14.3, tol=0.02)
# אישור צולב להפרדה: אותם 111 מילויים חלקי שני המכנים. שני המספרים
# נרשמו בקבצים נפרדים לפני שההפרדה נוסחה, ולכן הם עדות ולא הגדרה.
check("מילויים ליום מסחר שחלף", 111/41, 2.71, tol=0.01)
check("מילויים ליום-עסקה", 111/28, 3.96, tol=0.01)
# אופק הגילוי. שגיאת התקן נגזרת ממה שהריצה הדפיסה ולא נרשמת מהזיכרון:
# רווח [-0.197, +0.398] סביב +0.101R על 28 אשכולות.
check("מחצית-רווח שהודפסה", (0.398-(-0.197))/2, 0.2975, tol=0.01)
check("שגיאת תקן מקובצת נגזרת", 0.2975/2.0518, 0.145, tol=0.01)
check("כמה מזה מקיבוץ: יחס לעצמאות מלאה", 0.145/(1.45/111**0.5), 1.05, tol=0.02, unit="x")
# 39 ימי-עסקה ל-+0.250R, ו-2.7 חודשי לוח — לא 1.8 ולא 5.4.
check("חודשים ל-+0.250R", 39/(21*28/41), 2.7, tol=0.03)
check("אותו דבר בחלוקה שגויה ב-21", 39/21, 1.86, tol=0.03)
# חמישה מילויים בני-השוואה אינם חמישה ימי מסחר. התקרה בקונפיג היא
# עסקה אחת ביום, ורק 68% מימי המסחר בחלון הנקי הניבו מילוי בכלל,
# ולכן המספר הקובע הוא 5 חלקי 0.683 ולא 5.
from math import comb
def _at_least(k, n, p):
    return sum(comb(n, i) * p**i * (1-p)**(n-i) for i in range(k, n+1))
check("ימי מסחר בתוחלת לחמישה מילויים, עסקה ביום", 5/(28/41), 7.32, tol=0.02)
check("הסתברות לחמישה מילויים בחמישה ימים", _at_least(5, 5, 28/41), 0.148, tol=0.03)
check("הסתברות לחמישה מילויים בשמונה ימים", _at_least(5, 8, 28/41), 0.774, tol=0.02)
check("ימי מסחר ל-100 עסקאות בתקרה של אחת ביום", 100/(28/41), 146, tol=0.02)
for label, fill, want in (("50%", 0.50, 63), ("70%", 0.70, 45)):
    check(f"ימי מסחר ל-100 עסקאות, מילוי {label}",
          100/(131/41*fill), want, tol=0.03)
check("ימי מסחר ל-900 עסקאות, מילוי 70%", 900/(131/41*0.70), 402, tol=0.03)
check("חודשים ל-900 עסקאות, מילוי 70%", 900/(131/41*0.70)/21, 19.2, tol=0.03)
# עלות הגילוי בשער: הערכה, הפעלה, ורכישה חוזרת אחת.
check("עלות גילוי דרך השער", 40+85+40, 165, unit="$")
check("אותו דבר בלי רכישה חוזרת", 40+85, 125, unit="$")
# הצד השני מגיע מ-apex_model ולכן נבדק שם, לא כאן. מה שכן נבדק
